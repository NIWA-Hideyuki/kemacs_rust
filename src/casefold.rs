pub fn fold_char(c: char) -> char {
    if c.is_ascii() {
        return c.to_ascii_lowercase();
    }
    let mut lo = 0usize;
    let mut hi = CTAB.len();
    while lo < hi {
        let mid = (lo + hi) / 2;
        match CTAB[mid].0.cmp(&c) {
            std::cmp::Ordering::Less => lo = mid + 1,
            std::cmp::Ordering::Greater => hi = mid,
            std::cmp::Ordering::Equal => return CTAB[mid].1.to_ascii_lowercase(),
        }
    }
    c
}

/// パターン/行を比較用の正規形に変換する。
/// 返り値は (正規化バイト列, 正規化バイト位置 → 元バイト位置 の表)。
pub fn canonicalize(bytes: &[u8]) -> (Vec<u8>, Vec<usize>) {
    let text = String::from_utf8_lossy(bytes);
    let mut out = Vec::with_capacity(bytes.len());
    let mut map = Vec::with_capacity(bytes.len() + 1);
    let mut orig = 0usize;
    for ch in text.chars() {
        let c = fold_char(ch);
        let mut buf = [0u8; 4];
        let enc = c.encode_utf8(&mut buf).as_bytes();
        for &b in enc {
            out.push(b);
            map.push(orig);
        }
        orig += ch.len_utf8();
    }
    map.push(bytes.len());
    (out, map)
}

/// 元バイト位置 off 以上/以下の最初の正規化位置を返す。
pub fn canonical_index(map: &[usize], off: usize) -> usize {
    let mut i = 0usize;
    while i + 1 < map.len() && map[i] < off {
        i += 1;
    }
    i
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fullwidth_punctuation_and_kana_fold() {
        assert_eq!(fold_char('。'), '.');
        assert_eq!(fold_char('，'), ',');
        assert_eq!(fold_char('Ａ'), 'a');
        assert_eq!(fold_char('ア'), 'ｱ');
        assert_eq!(fold_char('あ'), 'ｱ');
        assert_eq!(fold_char('X'), 'x');
    }

    #[test]
    fn fullwidth_digits_fold_to_ascii() {
        for (fw, ascii) in [('０', '0'), ('１', '1'), ('９', '9')] {
            assert_eq!(fold_char(fw), ascii);
        }
    }

    #[test]
    fn canonicalize_maps_byte_offsets() {
        let (out, map) = canonicalize("a。B".as_bytes());
        assert_eq!(out, b"a.b");
        assert_eq!(map[0], 0);
        assert_eq!(map[1], 1);
        assert_eq!(map[2], 4);
        assert_eq!(map[3], 5);
        assert_eq!(canonical_index(&map, 1), 1);
    }
}
